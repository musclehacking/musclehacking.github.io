import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const repositoryRoot = fileURLToPath(new URL('../', import.meta.url));
const blogDirectory = fileURLToPath(new URL('../src/content/blog/', import.meta.url));
const outputFile = fileURLToPath(new URL('../src/config/blog-slugs.generated.ts', import.meta.url));
const checkOnly = process.argv.includes('--check');

const entries = await readdir(blogDirectory, { withFileTypes: true });
const contentFiles = entries.filter((entry) => entry.isFile() && /\.(?:md|mdx)$/.test(entry.name));
const publicationCutoff = new Date();

const publishedSlugs = await Promise.all(contentFiles.map(async (entry) => {
  const source = await readFile(new URL(`../src/content/blog/${entry.name}`, import.meta.url), 'utf8');
  const frontmatter = source.match(/^---\s*\n([\s\S]*?)\n---/u)?.[1] ?? '';
  const draft = /^draft:\s*true\s*$/mu.test(frontmatter);
  const publishedValue = frontmatter.match(/^published:\s*["']?([^"'\s]+)["']?\s*$/mu)?.[1];
  const published = publishedValue ? new Date(publishedValue) : undefined;

  if (draft || !published || Number.isNaN(published.valueOf()) || published > publicationCutoff) return undefined;
  return entry.name.replace(/\.(?:md|mdx)$/, '');
}));

const slugs = publishedSlugs
  .filter((slug) => slug !== undefined)
  .sort((left, right) => left.localeCompare(right));

const source = [
  '// This file is generated by scripts/sync-blog-slugs.mjs. Do not edit it by hand.',
  `export const blogSlugs = ${JSON.stringify(slugs, null, 2)} as const;`,
  '',
].join('\n');

if (checkOnly) {
  const current = await readFile(outputFile, 'utf8').catch(() => '');

  if (current !== source) {
    const displayPath = outputFile.replace(`${repositoryRoot}/`, '');
    console.error(`${displayPath} is stale; run node scripts/sync-blog-slugs.mjs`);
    process.exitCode = 1;
  }
} else {
  await writeFile(outputFile, source);
}
